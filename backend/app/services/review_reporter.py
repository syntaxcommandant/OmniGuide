import json
from typing import Dict, Any
from app.models.review import Review


def generate_review_report_markdown(review: Review) -> str:
    """Generates a structured markdown audit report for a single copy review."""
    created_dt = getattr(review, "created_at", None)
    if hasattr(created_dt, "strftime"):
        date_str = created_dt.strftime('%Y-%m-%d %H:%M UTC')
    else:
        date_str = str(created_dt) if created_dt else "Recent"

    status_str = getattr(review, "overall_status", "pending").upper()
    is_compliant = (getattr(review, "overall_status", "") == "compliant") or (len(getattr(review, "findings", [])) == 0)
    comp_badge = "COMPLIANT" if is_compliant else "NON_COMPLIANT / FLAGGED"

    lines = [
        "# OmniGuide Single Copy Governance Audit Report",
        f"**Report ID:** `REP-REV-{str(review.id)[:8]}` | **Review Title:** {review.title}",
        f"**Content Type:** {review.content_type} | **Evaluation Date:** {date_str}",
        f"**Overall Compliance:** `{comp_badge}` | **Workflow Status:** `{status_str}`",
        f"**Analysis Mode:** `{getattr(review, 'analysis_mode', 'hybrid').upper()}`",
        "",
        "## 1. Executive Summary",
        f"- **Original Submitted Copy Length:** {len(review.original_content)} characters",
        f"- **Findings Detected:** {len(review.findings)} finding(s)",
        f"- **Audit Resolution:** {'All findings reviewed & resolved' if status_str == 'RESOLVED' else 'Pending human reviewer decisions'}",
        "",
        "## 2. Copy Comparison & Provenance",
        "### Original Submitted Copy (Immutable)",
        f"> {review.original_content}",
        "",
        "### Approved Revised Copy",
        f"> {review.revised_content}",
        "",
        "## 3. Detailed Findings & Evidence Provenance",
        "| Severity | Category | Original Excerpt | Evidence Tier | Guideline Ref | Decision Status |",
        "| :--- | :--- | :--- | :--- | :--- | :--- |"
    ]

    for f in review.findings:
        g_ref = getattr(f, "guideline_clause_identifier", None) or getattr(f, "guideline_ref", None) or "General"
        lines.append(
            f"| `{f.severity}` | {f.category} | \"{f.original_excerpt}\" | `{getattr(f, 'evidence_tier', 'UNSUPPORTED')}` | {g_ref} | `{f.decision_status.upper()}` |"
        )

    lines.extend([
        "",
        "## 4. Remediation & Action Log",
    ])

    if hasattr(review, "actions") and review.actions:
        for act in review.actions:
            act_dt = getattr(act, "created_at", None)
            act_time = act_dt.strftime('%H:%M:%S UTC') if hasattr(act_dt, "strftime") else ""
            lines.append(f"- **[{act_time}] {act.action_type.upper()}:** {act.new_value or 'Action applied'}")
    else:
        lines.append("- *No subsequent reviewer modifications recorded.*")

    lines.extend([
        "",
        "---",
        "*Report generated by OmniGuide Brand Governance Platform. Evidence verified deterministically against approved guidelines.*",
        "*Policy Notice: A finding classified as 'UNSUPPORTED' reflects absence of registered evidence under the active policy, not an assertion of absolute falsity.*"
    ])

    return "\n".join(lines)


def generate_review_report_json(review: Review) -> Dict[str, Any]:
    """Generates a structured, machine-readable JSON audit report matching persisted review records."""
    created_dt = getattr(review, "created_at", None)
    date_str = created_dt.isoformat() if hasattr(created_dt, "isoformat") else str(created_dt)

    findings_list = []
    high_count = 0
    medium_count = 0
    low_count = 0

    for f in review.findings:
        if f.severity == "High":
            high_count += 1
        elif f.severity == "Medium":
            medium_count += 1
        else:
            low_count += 1

        prov_raw = getattr(f, "evidence_provenance", None)
        provenance = None
        if prov_raw:
            if isinstance(prov_raw, dict):
                provenance = prov_raw
            elif isinstance(prov_raw, str):
                try:
                    provenance = json.loads(prov_raw)
                except Exception:
                    provenance = {"raw": prov_raw}

        findings_list.append({
            "id": f.id,
            "category": f.category,
            "severity": f.severity,
            "original_excerpt": f.original_excerpt,
            "explanation": f.explanation,
            "guideline_ref": getattr(f, "guideline_clause_identifier", None) or getattr(f, "guideline_ref", None),
            "suggested_fix": f.suggested_fix,
            "evidence_tier": getattr(f, "evidence_tier", "UNSUPPORTED"),
            "evidence_quote": getattr(f, "guideline_clause_text", None) or getattr(f, "evidence_quote", None),
            "evidence_provenance": provenance,
            "decision_status": f.decision_status,
            "user_custom_fix": f.user_custom_fix,
            "created_at": (
                f.created_at.isoformat()
                if hasattr(f, "created_at") and hasattr(getattr(f, "created_at"), "isoformat")
                else date_str
            )
        })

    action_log = []
    if hasattr(review, "actions") and review.actions:
        for act in review.actions:
            action_log.append({
                "id": act.id,
                "action_type": act.action_type,
                "finding_id": act.finding_id,
                "previous_value": act.previous_value,
                "new_value": act.new_value,
                "created_at": act.created_at.isoformat() if hasattr(act.created_at, "isoformat") else str(act.created_at)
            })

    return {
        "report_id": f"REP-REV-{str(review.id)[:8]}",
        "report_type": "Single Copy Governance Audit",
        "governance_policy_version": "OmniGuide Policy Engine v1.3.0",
        "review_id": review.id,
        "title": review.title,
        "content_type": review.content_type,
        "campaign_context": getattr(review, "campaign_context", None),
        "analysis_mode": getattr(review, "analysis_mode", "hybrid"),
        "is_compliant": (getattr(review, "overall_status", "") == "compliant") or (len(getattr(review, "findings", [])) == 0),
        "overall_status": getattr(review, "overall_status", "pending"),
        "evaluation_timestamp": date_str,
        "original_content": review.original_content,
        "revised_content": review.revised_content,
        "findings_summary": {
            "total": len(review.findings),
            "high": high_count,
            "medium": medium_count,
            "low": low_count
        },
        "findings": findings_list,
        "reviewer_action_log": action_log,
        "policy_notice": "Claims flagged as 'UNSUPPORTED' reflect absence of approved evidence under the active policy, not a determination of factual falsity."
    }
